/**
 * Юнит-тест геометрии кластеров: чистые функции assets/puzzle-clusters.js,
 * без сервера/сокетов/DOM — единственный способ изолированно проверить
 * самое рискованное место (стыковку stitchGroup) до того, как оно
 * прогоняется через WS/браузер.
 *
 * Запуск: node test/unit-clusters.mjs
 */
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { tolerance, buildClusters, largestClusterSize, connectedPiecesCount, stitchGroup } = require("../assets/puzzle-clusters.js");

const CELL = 100;
const TOL = tolerance(CELL); // 28

let failures = 0;
const ok = (name, cond, extra = "") => {
  console.log(`${cond ? "  OK  " : " FAIL "} ${name}${extra ? " — " + extra : ""}`);
  if (!cond) failures++;
};
const near = (a, b, eps = 1e-6) => Math.abs(a - b) <= eps;

/* ── tolerance() ── */
ok("tolerance(100) === 28", near(TOL, 28));

/* ── buildClusters: базовая сборка кластеров по сетке ── */
{
  // Квадрат 2×2, все четыре детали идеально состыкованы.
  const pieces = [
    { r: 0, c: 0, x: 0, y: 0 },
    { r: 0, c: 1, x: 100, y: 0 },
    { r: 1, c: 0, x: 0, y: 100 },
    { r: 1, c: 1, x: 100, y: 100 },
  ];
  const { members } = buildClusters(pieces, CELL, TOL);
  ok("buildClusters: собранный квадрат — один кластер из 4", largestClusterSize(members) === 4);
}
{
  // Та же сетка, но одна деталь далеко — два кластера.
  const pieces = [
    { r: 0, c: 0, x: 0, y: 0 },
    { r: 0, c: 1, x: 100, y: 0 },
    { r: 1, c: 0, x: 0, y: 100 },
    { r: 1, c: 1, x: 9999, y: 9999 },
  ];
  const { members } = buildClusters(pieces, CELL, TOL);
  ok("buildClusters: оторванная деталь не входит в основной кластер", largestClusterSize(members) === 3);
  ok("buildClusters: всего кластеров — 2", members.size === 2);
}

/* ── connectedPiecesCount: счётчик "собрано" — сумма ВСЕХ кластеров от 2,
 * не только самого большого (регресс на запрос пользователя: раньше
 * счётчик использовал largestClusterSize, и деталь, состыкованная в
 * отдельный от основного кусок, в него не попадала). */
{
  // Два независимых кластера по 2 детали (не смежные друг с другом) +
  // одна ни с кем не состыкованная одиночка.
  const pieces = [
    { r: 0, c: 0, x: 0, y: 0 },
    { r: 0, c: 1, x: 100, y: 0 },       // состыкована с (0,0) — кластер А, 2 детали
    { r: 5, c: 5, x: 5000, y: 5000 },
    { r: 5, c: 6, x: 5100, y: 5000 },   // состыкована с (5,5) — кластер Б, 2 детали, ФИЗИЧЕСКИ далеко от А
    { r: 9, c: 9, x: 9999, y: 9999 },   // одиночка — ни с кем не состыкована
  ];
  const { members } = buildClusters(pieces, CELL, TOL);
  ok("connectedPiecesCount: largestClusterSize видит только больший (тут оба по 2 — 2)", largestClusterSize(members) === 2);
  ok("connectedPiecesCount: сумма ОБОИХ кластеров по 2 детали — 4, одиночка не в счёт",
    connectedPiecesCount(members) === 4, String(connectedPiecesCount(members)));
}
{
  // Всё врозь — ни одной стыковки вообще: счётчик должен быть 0, а не
  // "1" (размер тривиального кластера-одиночки).
  const pieces = [
    { r: 0, c: 0, x: 0, y: 0 },
    { r: 0, c: 1, x: 9999, y: 0 },
    { r: 1, c: 0, x: 0, y: 9999 },
  ];
  const { members } = buildClusters(pieces, CELL, TOL);
  ok("connectedPiecesCount: ни одной стыковки — счётчик 0", connectedPiecesCount(members) === 0);
}
{
  // Один большой кластер из всех — оба счётчика совпадают (единственный
  // случай, где largestClusterSize и connectedPiecesCount дают один
  // результат: когда кластер ровно один).
  const pieces = [
    { r: 0, c: 0, x: 0, y: 0 },
    { r: 0, c: 1, x: 100, y: 0 },
    { r: 1, c: 0, x: 0, y: 100 },
    { r: 1, c: 1, x: 100, y: 100 },
  ];
  const { members } = buildClusters(pieces, CELL, TOL);
  ok("connectedPiecesCount: единственный кластер — совпадает с largestClusterSize",
    connectedPiecesCount(members) === largestClusterSize(members) && connectedPiecesCount(members) === 4);
}

/* ── stitchGroup: одиночная стыковка ── */
{
  // Тащим одну деталь (0,0) рядом с неподвижным соседом (0,1), но не точно —
  // в пределах допуска (offset 10 < TOL=28).
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 0, y: 0 }],
    ["0,1", { r: 0, c: 1, x: 90, y: 3 }],
  ]);
  stitchGroup(pieces, new Set(["0,0"]), CELL, TOL);
  const a = pieces.get("0,0"), b = pieces.get("0,1");
  ok("stitchGroup: одиночная стыковка — точная стыковка по X", near(b.x - a.x, CELL));
  ok("stitchGroup: одиночная стыковка — точная стыковка по Y", near(b.y - a.y, 0));
  const { members } = buildClusters([...pieces.values()], CELL, TOL);
  ok("stitchGroup: после стыковки buildClusters видит один кластер из 2", largestClusterSize(members) === 2);
}

/* ── stitchGroup: деталь ВНЕ допуска не стыкуется ── */
{
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 0, y: 0 }],
    ["0,1", { r: 0, c: 1, x: 50, y: 0 }], // offset 50 от идеала (100) — вне допуска 28
  ]);
  stitchGroup(pieces, new Set(["0,0"]), CELL, TOL);
  const a = pieces.get("0,0"), b = pieces.get("0,1");
  ok("stitchGroup: деталь вне допуска не двигается", a.x === 0 && a.y === 0);
  ok("stitchGroup: сосед вне допуска остаётся несостыкованным", !near(b.x - a.x, CELL));
}

/* ── stitchGroup: цепная реакция — стыковка с двух сторон за один жест ──
 * Тащим жёсткую пару (1,0)+(1,1) (внутреннее взаимное расстояние уже верное:
 * ровно CELL по X) рядом с двумя неподвижными соседями сразу: (0,0) сверху
 * от (1,0) и (0,1) сверху от (1,1). Группа целиком смещена от идеала на
 * один и тот же (errX,errY) относительно обоих неподвижных соседей — стыковка
 * с одним автоматически выравнивает и второй за счёт жёсткости группы, что
 * stitchGroup обязан поймать за один вызов (перезапуск скана после каждого
 * успешного ребра).
 */
{
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 0, y: 0 }],       // неподвижный, стационарный
    ["0,1", { r: 0, c: 1, x: 100, y: 0 }],     // неподвижный, стационарный
    ["1,0", { r: 1, c: 0, x: 12, y: 108 }],    // тащим: сдвинуто от идеала (0,100) на (12,8)
    ["1,1", { r: 1, c: 1, x: 112, y: 108 }],   // тащим: та же жёсткая пара, сдвиг идентичен
  ]);
  const dragging = new Set(["1,0", "1,1"]);
  stitchGroup(pieces, dragging, CELL, TOL);
  const a00 = pieces.get("0,0"), a01 = pieces.get("0,1");
  const b10 = pieces.get("1,0"), b11 = pieces.get("1,1");
  ok("stitchGroup: цепная стыковка — левая пара точно под (0,0)", near(b10.x - a00.x, 0) && near(b10.y - a00.y, CELL));
  ok("stitchGroup: цепная стыковка — правая пара точно под (0,1)", near(b11.x - a01.x, 0) && near(b11.y - a01.y, CELL));
  ok("stitchGroup: внутренняя жёсткость пары сохранена", near(b11.x - b10.x, CELL) && near(b11.y - b10.y, 0));
  const { members } = buildClusters([...pieces.values()], CELL, TOL);
  ok("stitchGroup: после цепной стыковки — один кластер из 4", largestClusterSize(members) === 4);
}

/* ── stitchGroup: слияние ДВУХ уже многосоставных кластеров ──
 * Регресс на баг "перекос столбца после стыковки" (см. скриншот): деталь
 * может попасть в кластер через buildClusters ЛИШЬ по случайной близости
 * (в пределах допуска), ни разу не пройдя через явную стыковку именно
 * этого шва — например, она отдыхала где-то рядом и её раскладка случайно
 * совпала с "правильным" местом. Следующий stitchGroup, стыкующий её
 * кластер С ДРУГИМ кластером, видит эту пару как ВНУТРЕННЮЮ
 * (draggingKeys.has(nKey) — пропускается без проверки) и никогда её не
 * поправляет: неточность (до ±tol) навсегда "приклеивается" к кластеру и
 * при жёстком слиянии с посторонним кластером выглядит как перекос части
 * группы — именно так и воспроизвелось программно (см. план расследования).
 *
 * Левый кластер — {0,0;0,1}, собран одной явной стыковкой.
 * Правый кластер — {0,2;1,2;2,2}: (1,2) явно состыкована с (0,2) через
 * stitchGroup, а (2,2) НЕ состыкована явно — она просто оказалась в
 * пределах допуска (не идеально) от места под (1,2), buildClusters уже
 * признаёт кластер из 3 деталей, хотя шов (1,2)-(2,2) неточен.
 * Финальный жест — перетаскивание ВСЕГО правого кластера (все 3 детали,
 * как их реально захватил бы bindPieceDrag/bindRoomPieceDrag через
 * buildClusters) к левому, стыкуя только край (0,1)-(0,2).
 */
{
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 0, y: 0 }],
    ["0,1", { r: 0, c: 1, x: 95, y: -4 }], // раскладка рядом, в пределах допуска
    ["0,2", { r: 0, c: 2, x: 500, y: 500 }],
    ["1,2", { r: 1, c: 2, x: 508, y: 596 }], // раскладка рядом с (0,2), в пределах допуска
    ["2,2", { r: 2, c: 2, x: 512, y: 685 }], // НЕ дотащена явно — просто оказалась близко к идеалу под (1,2) (offset 12,-15, |err|≈19 < TOL=28)
  ]);

  // Левый кластер — явная стыковка.
  stitchGroup(pieces, new Set(["0,1"]), CELL, TOL);
  // Правый кластер — явно стыкуем только (1,2) с (0,2); (2,2) остаётся "приклеенной" случайно.
  stitchGroup(pieces, new Set(["1,2"]), CELL, TOL);

  const before = buildClusters([...pieces.values()], CELL, TOL);
  ok("регресс: правый кластер уже виден как одна группа из 3 ДО явной стыковки (2,2)",
    before.members.get(before.clusterOf.get("2,2")).size === 3);

  // Финальный жест: захватываем ВЕСЬ правый кластер (как это сделал бы
  // bindPieceDrag через buildClusters) и тащим к левому — стыкуется только
  // край (0,1)-(0,2), (1,2)-(2,2) — граница ВНУТРИ группы.
  const { clusterOf, members } = buildClusters([...pieces.values()], CELL, TOL);
  const rightGroup = members.get(clusterOf.get("0,2"));
  const target = { x: 200 + 5, y: 0 - 3 }; // около идеала (200,0) от (0,1), но не идеально точно
  const cur02 = pieces.get("0,2");
  const dx = target.x - cur02.x, dy = target.y - cur02.y;
  for (const k of rightGroup) { const p = pieces.get(k); p.x += dx; p.y += dy; }
  stitchGroup(pieces, rightGroup, CELL, TOL);

  const { members: finalMembers } = buildClusters([...pieces.values()], CELL, TOL);
  ok("регресс: после финального слияния — один кластер из 5", largestClusterSize(finalMembers) === 5 && finalMembers.size === 1);

  const p00 = pieces.get("0,0"), p01 = pieces.get("0,1"), p02 = pieces.get("0,2"), p12 = pieces.get("1,2"), p22 = pieces.get("2,2");
  ok("регресс: (0,0)-(0,1) точно по сетке", near(p01.x - p00.x, CELL) && near(p01.y - p00.y, 0));
  ok("регресс: (0,1)-(0,2) точно по сетке (шов финального слияния)", near(p02.x - p01.x, CELL) && near(p02.y - p01.y, 0));
  ok("регресс: (0,2)-(1,2) точно по сетке", near(p12.x - p02.x, 0) && near(p12.y - p02.y, CELL));
  ok("регресс: (1,2)-(2,2) точно по сетке — деталь, случайно 'приклеенная' в допуске, тоже выровнена ректификацией группы",
    near(p22.x - p12.x, 0) && near(p22.y - p12.y, CELL),
    `errX=${(p22.x - p12.x - 0).toFixed(3)} errY=${(p22.y - p12.y - CELL).toFixed(3)}`);
}

/* ── stitchGroup: скрытая неточность на НЕПОДВИЖНОЙ стороне тоже лечится ──
 * Живой репродукт (пользователь воспроизвёл вживую): криво прицепленный
 * кусок чинится, если его ещё раз потащить — то есть баг был не только в
 * том, что rectifyGroup не чистил draggingKeys (это уже исправлено выше),
 * а в том, что она чистит ТОЛЬКО draggingKeys — неточность на НЕПОДВИЖНОЙ
 * стороне (к которой стыкуются) rectifyGroup вообще не касалась. Стол в
 * комнате получает детали через входящий sync — деталь может "приклеиться"
 * к чужому кластеру в допуске так же, как и на перетаскиваемой стороне (см.
 * тест выше), просто на стороне, которая в ЭТОТ раз не тащится.
 *
 * Неподвижный кластер — {0,0;0,1;1,0}: (0,0)-(0,1) состыкованы явно, а
 * (1,0) НЕ состыкована явно с (0,0) — просто оказалась в пределах допуска.
 * Затем тащим одиночную деталь (0,2) и стыкуем её к (0,1) — это НЕ трогает
 * шов (0,0)-(1,0) напрямую (он вне draggingKeys), но должно почиститься
 * довыравниванием ВСЕГО получившегося кластера после стыковки.
 */
{
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 0, y: 0 }],
    ["0,1", { r: 0, c: 1, x: 96, y: 4 }],   // раскладка рядом, в пределах допуска
    ["1,0", { r: 1, c: 0, x: 9, y: 111 }],  // НЕ дотащена явно — просто близко к идеалу (0,100) под (0,0), offset (9,11), |err|≈14 < TOL=28
    ["0,2", { r: 0, c: 2, x: 400, y: 400 }],
  ]);

  // Неподвижный кластер собирается явной стыковкой только (0,0)-(0,1).
  stitchGroup(pieces, new Set(["0,1"]), CELL, TOL);
  const before = buildClusters([...pieces.values()], CELL, TOL);
  ok("неподвижная сторона: (1,0) уже виден как часть кластера ДО явной стыковки",
    before.members.get(before.clusterOf.get("1,0")).size === 3);

  // Тащим одиночную (0,2) к (0,1) — не идеально точно, но в допуске.
  const p01 = pieces.get("0,1"), p02 = pieces.get("0,2");
  p02.x = p01.x + CELL + 6; p02.y = p01.y - 5;
  stitchGroup(pieces, new Set(["0,2"]), CELL, TOL);

  const { members: finalMembers } = buildClusters([...pieces.values()], CELL, TOL);
  ok("неподвижная сторона: после стыковки — один кластер из 4", largestClusterSize(finalMembers) === 4 && finalMembers.size === 1);

  const p00 = pieces.get("0,0"), p10 = pieces.get("1,0");
  ok("неподвижная сторона: (0,0)-(1,0) точно по сетке — довыровнена, хотя её никто явно не тащил",
    near(p10.x - p00.x, 0) && near(p10.y - p00.y, CELL),
    `errX=${(p10.x - p00.x - 0).toFixed(3)} errY=${(p10.y - p00.y - CELL).toFixed(3)}`);
}

/* ── stitchGroup: рамка-выделение может тащить ФИЗИЧЕСКИ не связанные
 * детали разом (см. bindPieceDrag/marquee) — draggingKeys больше не
 * гарантированно один настоящий кластер. Регресс на баг "телепорт при
 * отпускании": старая rectifyGroup(draggingKeys) ставила КАЖДУЮ деталь
 * группы на "правильное" место сетки относительно случайного анкера, будто
 * вся draggingKeys — один собранный кусок, даже если её участники (r,c)
 * далеко друг от друга и никогда не стыковались.
 */
{
  // (0,0) и (5,5) — далеко друг от друга и по сетке, и физически (никогда
  // не тащились друг к другу) — просто оказались вместе в рамке-выделении и
  // потащены одним жестом, сохраняя текущий относительный сдвиг экрана.
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 300, y: 300 }],
    ["5,5", { r: 5, c: 5, x: 340, y: 320 }], // рядом на экране с (0,0), но НЕ на "идеальном" месте сетки относительно неё
  ]);
  const before55 = { ...pieces.get("5,5") };
  stitchGroup(pieces, new Set(["0,0", "5,5"]), CELL, TOL);
  const p00 = pieces.get("0,0"), p55 = pieces.get("5,5");
  ok("рамка: физически не связанные детали в группе — телепорта нет (0,0) на месте", p00.x === 300 && p00.y === 300);
  ok("рамка: физически не связанные детали в группе — телепорта нет (5,5) на месте",
    near(p55.x, before55.x) && near(p55.y, before55.y),
    `x=${p55.x} y=${p55.y}, было x=${before55.x} y=${before55.y}`);
}
{
  // Смешанный случай: уже собранная жёсткая пара (0,0)+(0,1) ПЛЮС
  // случайно попавшая в ту же рамку одиночка (9,9), не имеющая никакого
  // отношения к этой паре. Пара должна остаться жёсткой (и, если рядом
  // окажется в допуске сосед — состыковаться, как раньше), одиночку
  // трогать не должно вообще.
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 0, y: 0 }],
    ["0,1", { r: 0, c: 1, x: 100, y: 0 }], // уже идеально состыкована с (0,0)
    ["9,9", { r: 9, c: 9, x: 500, y: 500 }], // случайный пассажир той же рамки — далеко и по сетке, и физически
  ]);
  const before99 = { ...pieces.get("9,9") };
  stitchGroup(pieces, new Set(["0,0", "0,1", "9,9"]), CELL, TOL);
  const a = pieces.get("0,0"), b = pieces.get("0,1"), c = pieces.get("9,9");
  ok("рамка+пара: жёсткая пара внутри группы осталась жёсткой", near(b.x - a.x, CELL) && near(b.y - a.y, 0));
  ok("рамка+пара: посторонний пассажир группы не тронут",
    near(c.x, before99.x) && near(c.y, before99.y),
    `x=${c.x} y=${c.y}, было x=${before99.x} y=${before99.y}`);
}
{
  // Более глубокий вариант того же бага: ОДНА из подгрупп внутри draggingKeys
  // реально стыкуется с посторонним неподвижным соседом (не входящим в
  // draggingKeys) — а другая, физически с ней НЕ связанная подгруппа той же
  // рамки, оказывается рядом чисто случайно. Старая (уже частично
  // исправленная) версия внутри stitchGroup двигала ВСЮ draggingKeys разом
  // при срабатывании стыковки одной подгруппы (`for (const k of
  // draggingKeys) p.x += errX`) — второй, никак не связанной подгруппе
  // "прилетало" чужое смещение, то есть телепорт всё равно оставался, просто
  // требовал не просто рамки, а рамки + реальной стыковки одной из её частей.
  const pieces = new Map([
    ["0,0", { r: 0, c: 0, x: 0, y: 0 }],           // неподвижный, стационарный (НЕ в draggingKeys)
    ["0,1", { r: 0, c: 1, x: 92, y: 5 }],          // тащим: рядом с (0,0) в допуске — реально состыкуется
    ["9,9", { r: 9, c: 9, x: 700, y: 700 }],       // тащим: та же рамка, но физически не связана ни с чем
  ]);
  const before99 = { ...pieces.get("9,9") };
  stitchGroup(pieces, new Set(["0,1", "9,9"]), CELL, TOL);
  const a = pieces.get("0,0"), b = pieces.get("0,1"), c = pieces.get("9,9");
  ok("рамка/частичная стыковка: реально стыкуемая деталь встала на место", near(b.x - a.x, CELL) && near(b.y - a.y, 0));
  ok("рамка/частичная стыковка: несвязанный пассажир той же рамки не тронут чужой стыковкой",
    near(c.x, before99.x) && near(c.y, before99.y),
    `x=${c.x} y=${c.y}, было x=${before99.x} y=${before99.y}`);
}

process.exit(failures ? 1 : 0);
